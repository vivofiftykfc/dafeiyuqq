const fs=require('fs'),os=require('os'),path=require('path'),vm=require('vm'),assert=require('assert');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'dafeiyu-dsh-'));
fs.mkdirSync(path.join(root,'runtime'));
fs.mkdirSync(path.join(root,'local'));
const roles=path.join(root,'local/tavern.json');
fs.writeFileSync(roles,JSON.stringify({roles:{private:{avatar:'A.png'}}}));
const job={id:'eval:tools',scope:'private',avatar:'A.png',state:'running'};
const jobs=path.join(root,'runtime/tavern-jobs.json');
fs.writeFileSync(jobs,JSON.stringify({[job.id]:job}));
fs.writeFileSync(path.join(root,'runtime/owner-ops.json'),JSON.stringify({token:'local-test-only'}));
const input=path.join(root,'input.json');fs.writeFileSync(input,JSON.stringify({job:{...job,turnContext:''},persona:'Card {{literal}}',visualEvidence:{event_id:'exact-image',preview_attached:false},history:[{speaker:'user',text:'literal {{not_a_variable}}'}],memories:[]}));
const calls=[],sections=[],tools={};
const context={fs,path,defineTool:x=>x,AbortSignal,Date,fetch:async(url,options)=>{
 calls.push({url,options});
 return options?{ok:true,status:200,json:async()=>({total:1,items:[]})}:{headers:{getSetCookie:()=>['csrf-secret=test; Path=/; HttpOnly']},json:async()=>({token:'csrf-token'})};
}};
vm.createContext(context);
const code=fs.readFileSync('integration/dsh-wechat-context/index.mjs','utf8').replace(/^import[^\n]+\n/gm,'').replace(/export /g,'');
vm.runInContext(code+'\nglobalThis.initialize=apply;',context);
(async()=>{
 context.initialize({systemPrompt:{section:value=>sections.push(value)},tools:{register:value=>tools[value.name]=value}},{root,input});
 const history=sections.find(row=>row.name==='wechat:verified-history');
 assert.equal(history.interpolate,false);assert(history.text().includes('{{not_a_variable}}'));
 assert(history.text().includes('"preview_attached":false'));
 assert.equal(sections.find(row=>row.name==='wechat:selected-persona').text(),'Card {{literal}}');
 await tools.sticker_inventory.execute({query:'西瓜',job_id:'forged-other-chat'});
 assert.equal(calls[1].options.headers.Cookie,'csrf-secret=test');
 assert.equal(calls[1].options.headers['X-CSRF-Token'],'csrf-token');
 assert.equal(JSON.parse(calls[1].options.body).job_id,job.id,'caller cannot override source binding');
 const candidate=await tools.prepare_reply.execute({message1:'嘿',message2:'在呢'});
 assert.equal(candidate.wechat_sent,false);
 const staged=JSON.parse(fs.readFileSync(input.replace(/\.json$/,'.candidate.json'),'utf8'));
 assert.deepEqual(staged.messages,['嘿','在呢']);
 assert.equal(staged.job_id,job.id);
 assert.throws(()=>tools.prepare_reply.execute({message1:'different reply'}),/already prepared/);
 await assert.rejects(()=>tools.synthesize_speech.execute({text:'hello'}),/real chat request/);
 await assert.rejects(async()=>tools.draw_image.execute({prompt:'whale'}),/real owner request/);
 await assert.rejects(()=>tools.read_moments.execute({limit:5}),/real owner request/);
 assert.equal(calls.length,2,'evaluation cannot generate speech or contact media service');
 fs.writeFileSync(roles,JSON.stringify({roles:{private:{avatar:'B.png'}}}));
 await assert.rejects(()=>tools.sticker_inventory.execute({query:'x'}),/role changed/);
 assert.equal(calls.length,2,'selected role change rejected before network');
 fs.writeFileSync(roles,JSON.stringify({roles:{private:{avatar:'A.png'}}}));
 fs.writeFileSync(jobs,JSON.stringify({[job.id]:{...job,dshDeadline:Date.now()-1}}));
 await assert.rejects(()=>tools.sticker_inventory.execute({query:'x'}),/expired/);
 assert.equal(calls.length,2,'late tool action rejected before network');
 fs.writeFileSync(jobs,JSON.stringify({[job.id]:{...job,avatar:'B.png'}}));
 await assert.rejects(()=>tools.sticker_inventory.execute({query:'x'}),/changed/);
 assert.equal(calls.length,2,'stale role rejected before network');
 console.log('DSH context preserves literal history; tool cookies and active-role binding verified');
})().catch(error=>{console.error(error);process.exitCode=1}).finally(()=>fs.rmSync(root,{recursive:true,force:true}));
