import assert from 'node:assert/strict';
import {mediaClaimIssues,reviewMediaReply,mediaNarrationIssues,repeatedImageCallbacks} from './tavern-extension/reply-delivery.mjs';
const evidence=[{watched_entire_video:false}];
for(const text of ['看完了亲爱的，不是只看标题','看完就懂那个笑点了','我看完之后觉得很荒诞'])assert(mediaClaimIssues(text,evidence).length);
for(const text of ['我没看完，只知道这段','我还不能说完整看过','这段挺逗，两颗球都在球门前','你看完之后也可以说说感想','看完这几帧，我只知道有两颗球'])assert.equal(mediaClaimIssues(text,evidence).length,0,text);
assert.equal(mediaClaimIssues('看完了',[]).length,0);
assert(mediaClaimIssues('看了一半就心虚了',evidence).length);
assert(mediaClaimIssues('我还没看清就播完了',evidence).length);
assert.equal(mediaClaimIssues('如果我看完之后再聊呢',evidence).length,0);
assert(mediaNarrationIssues('我抽的几帧几乎一模一样',evidence,'点评一下这个视频').length);
assert.equal(mediaNarrationIssues('我抽的几帧几乎一模一样',evidence,'你真的读到了吗，还是只看标题').length,0);
let calls=0;
const revised=await reviewMediaReply('看完了，最惨的是那位主人',evidence,async()=>{calls++;return '最惨的是那位主人，这鱼怎么还把游戏库公开了'});
assert.equal(calls,1);assert.equal(revised.audit.outcome,'revised');assert(revised.text.includes('游戏库'));
const fallback=await reviewMediaReply('看完了。这守门员到底该防哪个球啊，太难了。',evidence,async()=>{calls++;throw Error('unavailable')});
assert.equal(calls,2);assert.equal(fallback.text,'这守门员到底该防哪个球啊，太难了。');
await reviewMediaReply('就是这鱼闯祸了',evidence,async()=>{throw Error('unnecessary revision')});
assert.equal(calls,2);
console.log('PASS: one text-only media revision, finite fallback, concrete comment preserved and no unrelated rewrite');
const history=['我去端白饭','又在抢白饭','这笑容比我端白饭还紧'].map(mes=>({is_user:false,mes}));
assert(repeatedImageCallbacks(history,'[图片]','一只猫咪的表情').some(row=>row.word==='白饭'));
assert.equal(repeatedImageCallbacks(history,'你刚才为什么说白饭').length,0);
assert.equal(repeatedImageCallbacks(history,'[图片]','这张图片写着白饭').length,0);
assert.equal(repeatedImageCallbacks(history.slice(0,2),'[图片]').length,0);
let callbackCalls=0;
const fresh=await reviewMediaReply('我端饭时就是这样',[],async(issues,hints)=>{callbackCalls++;assert(issues.includes('repeated_own_image_callback'));assert(hints.length);return '这猫一脸刚睡醒就被薅起来的怨念'},'[图片]',history,'猫咪怼脸');
assert.equal(callbackCalls,1);assert(fresh.text.includes('猫'));assert.equal(fresh.audit.revision_tools,'none');
const kept=await reviewMediaReply('这猫一脸不服',[],async()=>{throw Error('offline')},'[图片]',history,'猫咪怼脸');
assert.equal(kept.text,'这猫一脸不服','a soft hint must not delete an otherwise valid reply');
const silent=await reviewMediaReply('<SKIP>',[],async()=>{throw Error('silence must not trigger generation')},'[图片]',history,'猫咪怼脸');
assert.equal(silent.text,'<SKIP>');assert.equal(silent.audit.attempted,false);
