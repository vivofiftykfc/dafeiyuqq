const managed=['preset-dafeiyu-owner','mcp-dafeiyu-owner','mcp-dafeiyu-phone'];
patches=patches.filter(x=>!managed.includes(x.id)).map(x=>x.insert?{...x,insert:x.insert.filter(y=>!managed.includes(y.id))}:x).filter(x=>!x.insert||x.insert.length);
const source=fs.readFileSync(path.join(root,'..','downloads','standard-preset-original.yml'),'utf8').replace(/!!js process\.platform === 'win32'/g,'true').replace(/!!js process\.platform !== 'win32'/g,'false');
const row=yaml.load(source)[0].insert[0];
row.id='preset-dafeiyu-owner';row.config.id='dafeiyu-owner';row.config.name='蓝色大肥鱼 · 个人私聊';row.config.order=15;
const persona=row.config.plugins.find(x=>x.id==='persona');
persona.name='qq-agent-presets/owner-memory-v2.mjs';
delete persona.config;
patches.push({insert:[row,{id:'mcp-dafeiyu-owner',name:'@deepseek-ai/dsh-mcp-client',config:{serverName:'dafeiyu-owner',transport:'stdio',command:path.join(root,'..','snowluma','node.exe'),args:[path.join(root,'src','mcp-owner.js'),'--memory-library-v9-growth'],toolCallTimeoutMs:90000}},{id:'mcp-dafeiyu-phone',name:'@deepseek-ai/dsh-mcp-client',config:{serverName:'dafeiyu-phone',transport:'stdio',command:path.join(root,'..','snowluma','node.exe'),args:[path.join(root,'src','mcp-owner-phone.js'),'--audit-v4-public-home-ime'],toolCallTimeoutMs:90000}}]});
for(const p of patches)if(p.id==='agent-default-model')p.config.reasoningEffort='high';
const permission=patches.find(x=>x.id==='permission');
if(permission)permission.config={...permission.config,defaultPreset:'danger-full-access'};
else patches.push({id:'permission',config:{defaultPreset:'danger-full-access'}});
fs.writeFileSync(patchFile,yaml.dump(patches,{lineWidth:-1}));
const manifestFile=path.join(root,'..','assets','identity','manifest.json');
const identity=JSON.parse(fs.readFileSync(manifestFile,'utf8'));
identity.visual_prompt='DeepSeek 小鲸鱼 Q 版形象：蓝白配色、蓝色长发、蓝色鲸鱼尾巴，圆润可爱的小鲸鱼拟人角色。保持参考图的蓝发、鲸鳍与鲸尾特征，但采用 Q 版比例；服装随场景，不默认女仆装。';
fs.writeFileSync(manifestFile,JSON.stringify(identity,null,2));
