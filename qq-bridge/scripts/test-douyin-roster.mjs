import fs from 'node:fs';import os from 'node:os';import path from 'node:path';import assert from 'node:assert/strict';
import {DouyinDirect} from '../src/douyin-direct.js';
import {ChatMemory} from '../src/chat-memory.js';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'douyin-roster-'));fs.mkdirSync(path.join(dir,'douyin-direct'));
fs.writeFileSync(path.join(dir,'douyin-direct/binding.json'),JSON.stringify({uid:'111',friends:{example_friend:'222'}}));
const memory=new ChatMemory(path.join(dir,'memory.sqlite'));
const c=new DouyinDirect(dir,{model:{reply:async()=>''},memory});
c.connected=true;c.account={online:true,getFriendList:async()=>[{uid:'222',nickname:'example_friend'},{uid:'333',nickname:'example_friend'},{uid:'444',nickname:'<script>名字</script>'}]};
await assert.rejects(c.updateRoster('add','999'),/已有好友/);
await c.updateRoster('add','333');assert.equal(c.status().roster.find(f=>f.uid==='333').reply,false);
assert.notEqual(c.status().roster.find(f=>f.uid==='333').name,'example_friend');
await c.updateRoster('reply','333',true);assert(c.status().roster.find(f=>f.uid==='333').reply);
await c.updateRoster('reply','222',false);assert(!c.friends.includes('example_friend'));
const restored=new DouyinDirect(dir,{model:{},memory});assert.deepEqual(restored.friends,c.friends);assert.equal(restored.enabled,false);
let cancelled=false;c.queue.stop=()=>{cancelled=true;};c.enabled=true;c.start=()=>{throw Error('should not start with empty roster')};
await c.updateRoster('remove','333');assert(cancelled);assert.equal(c.enabled,false);assert(!c.status().roster.some(f=>f.uid==='333'));
await assert.rejects(c.updateRoster('reply','222','true'),/布尔/);
await assert.rejects(c.updateRoster('add','222'),/已在名单/);
await c.updateRoster('add','444');assert(c.status().roster.some(f=>f.name.startsWith('<script>')));
console.log('PASS: verified contacts only / default off / same-name isolation / reply toggle persistence / restart off / removal cancels / input validation');
memory.close();
