import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildConversationInput} from '../src/douyin-model.js';
import {parseMediaReply} from '../src/douyin-media.js';
import {publicPersona} from '../plugins/qq-agent-presets/douyin-chat.mjs';
import {DirectReplyQueue} from '../src/douyin-direct-queue.js';
const long='长消息'.repeat(1000)+'结尾约定：紫色星期四';
const messages=Array.from({length:40},(_,i)=>({id:i+1,direction:'in',text:i===0?long:'消息'+i}));
const first=buildConversationInput({friend:'隔离测试',messages,key:'test'});
assert(first.prompt.includes(long));assert(first.prompt.includes('消息39'));
const delta=buildConversationInput({friend:'隔离测试',messages:[...messages,{id:41,direction:'in',text:'下一轮'}],key:'test',entry:{cursor:40,summaryHash:first.summaryHash}});
assert(!delta.prompt.includes(long));assert(delta.prompt.includes('下一轮'));
assert.equal(parseMediaReply(JSON.stringify({text:'解释'.repeat(1000)}),[]).text.length,2000);
assert(!publicPersona().includes('最多180字'));
const direct=fs.readFileSync(new URL('../src/douyin-direct.js',import.meta.url),'utf8');
assert(!direct.includes('await this.mediaModel.reply'));assert(direct.includes('kind,images'));
let received,discarded=0,release;
const q=new DirectReplyQueue({debounce:1,model:{reply:async(...args)=>{received=args;return new Promise(r=>release=r);},discard:async()=>discarded++},send:async()=>{throw Error('must not send stale candidate');}});
q.start([['peer','好友']],'account');
q.receive({uid:'peer',id:'1',accountUid:'account',time:Date.now()+1,text:'看图',images:[{type:'image',data:'fixture'}]});
await new Promise(r=>setTimeout(r,15));assert.equal(received[4][0].data,'fixture');
q.stop();release('过期候选');await new Promise(r=>setTimeout(r,15));assert.equal(discarded,1);
console.log('PASS: full 40-turn recovery, long-tail preservation, incremental input, >300-char replies, direct image path, no 180-char persona cap');
